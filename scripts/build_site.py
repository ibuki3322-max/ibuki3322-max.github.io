#!/usr/bin/env python3
"""Regenerate the app list and multiplayer cards from data/apps.json."""

import html
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
APPS = json.loads((ROOT / "data/apps.json").read_text(encoding="utf-8"))
SITE_URL = "https://ibuki3322-max.github.io/"


def escape(value):
    return html.escape(str(value), quote=True)


def render_app_card(app):
    app_id = escape(app["id"])
    name = escape(app["name"])
    category = escape(app["categoryName"])
    tag = f' • {escape(app["tag"])}' if app.get("tag") else ""
    platforms = "無料 (iOS / Android)" if app.get("googlePlayUrl") else "無料 (iOS)"
    official_link = (
        f'<a class="app-official-link" href="{escape(app["officialUrl"])}" target="_blank" rel="noopener noreferrer">公式サイト ↗</a>'
        if app.get("officialUrl") else ""
    )
    android_test_link = (
        f'<a class="app-android-test-link" href="{escape(app["androidTestUrl"])}" target="_blank" rel="noopener noreferrer">Androidテスター案内 ↗</a>'
        if app.get("androidTestUrl") else ""
    )
    return f'''<div class="app-card" data-app-id="{app_id}">
                    <div>
                        <div class="app-card-top">
                            <a href="apps/{app_id}.html" style="flex-shrink: 0;">
                                <img src="{escape(app["icon"])}" alt="{name}" class="app-icon" style="width: 58px; height: 58px;" loading="lazy">
                            </a>
                            <div style="min-width: 0; flex: 1;">
                                <div style="font-size: 0.72rem; color: #86868B; margin-bottom: 0.15rem;">{category}{tag}</div>
                                <h3 class="app-card-title"><a href="apps/{app_id}.html">{name}</a></h3>
                                <div class="app-card-sub">{escape(app.get("subtitle", ""))}</div>
                            </div>
                        </div>
                        <p class="app-card-desc">{escape(app["desc"])}</p>
                        {official_link}{android_test_link}
                    </div>
                    <div class="app-card-bottom">
                        <span class="app-card-tag">{platforms}</span>
                        <div style="display: flex; align-items: center; gap: 0.4rem;">
                            <a href="apps/{app_id}.html" class="btn-get" style="background: rgba(0,0,0,0.04); color: #1D1D1F;"><span>詳細</span></a>
                            <a href="{escape(app["url"])}" target="_blank" rel="noopener noreferrer" class="btn-get"><span>入手</span></a>
                        </div>
                    </div>
                </div>'''


def render_game_card(app):
    game = app["multiplayer"]
    title = escape(game["title"])
    tags = "".join(
        f'<span class="mode-tag mode-{escape(tag["mode"])}">{escape(tag["label"])}</span>'
        for tag in game["tags"]
    )
    official_link = (
        f'<a class="game-official-link" href="{escape(app["officialUrl"])}" target="_blank" rel="noopener noreferrer">公式サイト ↗</a>'
        if app.get("officialUrl") else ""
    )
    android_test_link = (
        f'<a class="game-android-test-link" href="{escape(app["androidTestUrl"])}" target="_blank" rel="noopener noreferrer">Androidテスター案内 ↗</a>'
        if app.get("androidTestUrl") else ""
    )
    return f'''<article class="game-card" data-modes="{escape(" ".join(game["modes"]))}">
        <div class="game-head">
            <img src="{escape(app["icon"])}" alt="" width="72" height="72" loading="lazy" class="game-icon">
            <div class="game-ident"><h3>{title}</h3><span class="player-count">{escape(game["playerCount"])}</span></div>
        </div>
        <p class="game-summary">{escape(game["summary"])}</p>
        <div class="game-tags">{tags}</div>
        <div class="game-external-links">{official_link}{android_test_link}</div>
        <div class="game-actions">
            <a class="detail-link" href="apps/{escape(app["id"])}.html" aria-label="{title} の詳細を見る">詳細を見る <span aria-hidden="true">↗</span></a>
            <a class="store-link" href="{escape(app["url"])}" target="_blank" rel="noopener noreferrer" aria-label="{title} をApp Storeで見る">App Store</a>
        </div>
    </article>'''


def main():
    ids = [app["id"] for app in APPS]
    if len(ids) != len(set(ids)):
        raise ValueError("Duplicate app IDs in data/apps.json")
    for app in APPS:
        if not (ROOT / "apps" / f'{app["id"]}.html').is_file():
            raise ValueError(f'Missing detail page: {app["id"]}')
        game = app.get("multiplayer")
        if game and (not game["modes"] or not game["tags"]):
            raise ValueError(f'Incomplete multiplayer details: {app["id"]}')

    js = "// Generated by scripts/build_site.py from data/apps.json.\nconst APPS_DATA = "
    js += json.dumps(APPS, ensure_ascii=False, separators=(",", ":")) + ";\n"
    (ROOT / "assets/apps-data.js").write_text(js, encoding="utf-8")

    home_path = ROOT / "index.html"
    home = home_path.read_text(encoding="utf-8")
    home = re.sub(r'ゲーム・ライフスタイル・仕事効率化など\d+本',
                  f'ゲーム・ライフスタイル・仕事効率化など{len(APPS)}本', home, count=1)
    home = re.sub(r'注目の\d+作品をピックアップ',
                  f'注目の{sum(bool(app.get("featured")) for app in APPS)}作品をピックアップ', home, count=1)
    home = re.sub(r'全 \d+ 作品を掲載', f'全 {len(APPS)} 作品を掲載', home, count=1)
    app_html = "\n" + "\n".join(render_app_card(app) for app in APPS) + "\n"
    app_start_marker = "<!-- BEGIN GENERATED APP CARDS -->"
    app_end_marker = "<!-- END GENERATED APP CARDS -->"
    if app_start_marker in home and app_end_marker in home:
        start = home.index(app_start_marker) + len(app_start_marker)
        end = home.index(app_end_marker, start)
        home = home[:start] + app_html + home[end:]
    else:
        placeholder = '<div class="apps-grid" id="appsGridContainer"></div>'
        if placeholder not in home:
            raise ValueError("App grid markers or empty placeholder not found in index.html")
        home = home.replace(placeholder,
                            f'<div class="apps-grid" id="appsGridContainer">{app_start_marker}{app_html}{app_end_marker}</div>',
                            1)
    home_path.write_text(home, encoding="utf-8")

    sitemap_urls = [SITE_URL, SITE_URL + "multiplayer.html"]
    sitemap_urls += [SITE_URL + f'apps/{app["id"]}.html' for app in APPS]
    sitemap = '<?xml version="1.0" encoding="UTF-8"?>\n'
    sitemap += '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
    sitemap += "".join(f'  <url><loc>{escape(url)}</loc></url>\n' for url in sitemap_urls)
    sitemap += '</urlset>\n'
    (ROOT / "sitemap.xml").write_text(sitemap, encoding="utf-8")
    (ROOT / "robots.txt").write_text(f'Sitemap: {SITE_URL}sitemap.xml\n', encoding="utf-8")

    games = sorted((app for app in APPS if app.get("multiplayer")),
                   key=lambda app: app["multiplayer"]["order"])
    game_html = "\n" + "\n".join(render_game_card(app) for app in games) + "\n"
    game_path = ROOT / "multiplayer.html"
    page = game_path.read_text(encoding="utf-8")
    start_marker = "<!-- BEGIN GENERATED GAME CARDS -->"
    end_marker = "<!-- END GENERATED GAME CARDS -->"
    if start_marker in page and end_marker in page:
        start = page.index(start_marker) + len(start_marker)
        end = page.index(end_marker, start)
        page = page[:start] + game_html + page[end:]
    else:
        start = page.index('<div class="game-grid" id="gameGrid">') + len('<div class="game-grid" id="gameGrid">')
        end = page.index('</article></div>', start) + len('</article>')
        page = page[:start] + start_marker + game_html + end_marker + page[end:]
    page = re.sub(r'(<span class="result-count" id="resultCount" aria-live="polite">)\d+作品',
                  lambda match: match.group(1) + f'{len(games)}作品', page, count=1)
    game_path.write_text(page, encoding="utf-8")
    print(f"Built {len(APPS)} apps, {len(games)} multiplayer games")


if __name__ == "__main__":
    main()
